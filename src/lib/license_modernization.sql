-- 1. Add quota_mode to existing licenses table
ALTER TABLE public.licenses 
  ADD COLUMN IF NOT EXISTS quota_mode VARCHAR(16) DEFAULT 'isolated';

-- 2. Classify existing all-access licenses as shared, service-restricted as isolated
UPDATE public.licenses
SET quota_mode = 'shared'
WHERE package_id IS NULL 
  AND id NOT IN (SELECT DISTINCT license_id FROM public.license_services);

UPDATE public.licenses
SET quota_mode = 'isolated'
WHERE quota_mode IS NULL;

-- 3. Create granular daily usage ledger
CREATE TABLE IF NOT EXISTS public.license_daily_usages (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_id    UUID NOT NULL REFERENCES public.licenses(id) ON DELETE CASCADE,
    discord_id    VARCHAR(32) NOT NULL,
    service_name  VARCHAR(64) NOT NULL,
    usage_date    DATE DEFAULT CURRENT_DATE,
    used_count    INT DEFAULT 0,
    updated_at    TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_license_service_date UNIQUE (license_id, service_name, usage_date)
);

CREATE INDEX IF NOT EXISTS idx_lic_daily_usage_lookup 
  ON public.license_daily_usages (license_id, usage_date);

CREATE INDEX IF NOT EXISTS idx_lic_daily_usage_user 
  ON public.license_daily_usages (discord_id, usage_date);

-- 4. Seed today's active counts from user_limits with explicit UUID casting
INSERT INTO public.license_daily_usages (license_id, discord_id, service_name, usage_date, used_count, updated_at)
SELECT 
    ul.license_id::uuid,
    ul.discord_user_id,
    'general',
    CURRENT_DATE,
    COALESCE(ul.count, 0),
    NOW()
FROM public.user_limits ul
INNER JOIN public.licenses l ON l.id = ul.license_id::uuid
WHERE ul.count > 0
ON CONFLICT (license_id, service_name, usage_date) 
DO UPDATE SET used_count = EXCLUDED.used_count;

